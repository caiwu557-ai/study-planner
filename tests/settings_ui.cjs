const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 } });
  const page = await context.newPage();
  const errors = [];
  const taskTitle = '快捷键提交测试 ' + Date.now();
  page.on('pageerror', e => errors.push(e.message));
  const base = 'http://127.0.0.1:18765';
  const shots = path.join(__dirname, '../shots/settings');
  fs.mkdirSync(shots, { recursive: true });
  async function blur() { await page.evaluate(() => document.activeElement.blur()); }
  try {
    await page.goto(base + '/#/settings');
    await page.locator('.theme-swatch').first().waitFor();
    assert.equal(await page.locator('#themeNameInput').count(), 0);
    assert.equal(await page.getByText('下载格式样例', { exact: true }).count(), 0);
    const [download] = await Promise.all([page.waitForEvent('download'), page.locator('.skill-link').click()]);
    assert.equal(download.suggestedFilename(), 'SKILL.md');
    const skill = fs.readFileSync(await download.path(), 'utf8');
    assert(skill.includes('```json') && skill.includes('study-planner-schedule'));
    assert.equal(skill, fs.readFileSync(path.join(__dirname, '../.agents/skills/study-planner-schedule/SKILL.md'), 'utf8'));
    const left = await page.locator('.appearance-themes').boundingBox();
    const right = await page.locator('.appearance-controls').boundingBox();
    assert(right.x > left.x + left.width && Math.abs(left.y - right.y) < 1);
    await page.locator('[data-theme="margarita"]').click();
    assert(await page.locator('#accentInput').isDisabled());
    assert(await page.locator('#presetNote').isVisible());
    await page.locator('[data-theme="mono"]').click();
    assert(await page.locator('#accentInput').isEnabled());
    assert.equal(await page.locator('#accent2Field').isVisible(), false);
    await page.locator('[data-theme="lemon-salt"]').click();
    const oldDensity = await page.locator('#densityInput').evaluate(el => el.value);
    await page.locator('#densityInput').click();
    assert.notEqual(await page.locator('#densityInput').evaluate(el => el.value), oldDensity);
    assert.equal(await page.locator('.density-thumb').textContent(), oldDensity === 'compact' ? '舒展' : '紧凑');
    assert.equal(await page.locator('body').getAttribute('data-density'), oldDensity === 'compact' ? 'comfortable' : 'compact');
    await page.locator('#fontScaleInput').fill('18');
    assert.equal(await page.locator('#fontSizeValue').textContent(), '18 px');
    const fontMetrics = await page.evaluate(() => ({ base: parseFloat(getComputedStyle(document.body).fontSize), title: parseFloat(getComputedStyle(document.querySelector('#settingsView h1')).fontSize) }));
    assert(Math.abs(fontMetrics.base - 18) < .01 && Math.abs(fontMetrics.title - 38 * 18 / 14) < .01, JSON.stringify(fontMetrics));
    await page.locator('#fontScaleInput').focus();
    const settingsRoute = page.url();
    await page.keyboard.press('ArrowRight');
    assert.equal(await page.locator('#fontScaleInput').inputValue(), '19');
    assert.equal(page.url(), settingsRoute);
    await page.locator('#appearanceForm button[type="submit"]').click();
    await page.getByText('外观设置已保存', { exact: true }).waitFor();
    await page.reload();
    await page.waitForFunction(() => document.getElementById('fontScaleInput').value === '19');
    assert.equal(await page.locator('#densityInput').evaluate(el => el.value), oldDensity === 'compact' ? 'comfortable' : 'compact');
    await page.locator('#fontScaleInput').fill('14');
    await page.locator('#appearanceForm button[type="submit"]').click();
    await page.waitForFunction(() => parseFloat(getComputedStyle(document.body).fontSize) === 14);
    await page.locator('#appearanceForm').screenshot({ path: path.join(shots, 'appearance.png') });

    await page.locator('#aiModelInput').fill('typing-test');
    await page.keyboard.press('Alt+3');
    await page.keyboard.press('b');
    assert.equal(page.url(), settingsRoute, 'input editing must not navigate');
    await blur();
    await page.keyboard.press('Control+k');
    await page.keyboard.press('Escape');
    await page.waitForTimeout(120);
    assert(await page.evaluate(() => !document.getElementById('quickAddModal').contains(document.activeElement)), 'fast close must not return focus to a hidden input');
    const routes = ['home/', 'reviews', 'todos', 'ddls', 'calendar/', 'settings'];
    for (let i = 0; i < routes.length; i++) {
      await page.keyboard.press('Alt+' + (i + 1));
      await page.waitForURL(url => url.hash.startsWith('#/' + routes[i]));
      await page.locator('.nav-item.active').filter({ hasText: ['首页', '复习清单', '待办清单', '到期清单', '日历看板', '设置'][i] }).waitFor();
    }
    await page.keyboard.press('b');
    const collapsed = await page.locator('#app').getAttribute('class');
    await page.keyboard.press('b');
    assert.notEqual(await page.locator('#app').getAttribute('class'), collapsed);
    await page.keyboard.press('Control+k');
    await page.locator('#quickAddModal.open').waitFor();
    await page.locator('#taskTitle').fill(taskTitle);
    await page.keyboard.press('Control+k');
    assert.equal(await page.locator('#taskTitle').inputValue(), taskTitle, 'reopening must not erase the draft');
    await page.keyboard.press('Alt+5');
    assert.equal(page.url(), settingsRoute, 'modal editing must not navigate');
    await page.keyboard.press('Control+Enter');
    await page.waitForFunction(() => !document.querySelector('#quickAddModal.open'));
    await page.keyboard.press('Alt+3');
    await page.waitForURL(url => url.hash.startsWith('#/todos'));
    await page.locator('#todosView .task-item .edit-task').first().click();
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('.inline-task-editor').count(), 0);
    await blur();
    await page.keyboard.press('Alt+5');
    await page.waitForURL('**/#/calendar/**');
    await page.locator('#calendarView.active-view').waitFor();
    await page.keyboard.press('m');
    await page.waitForURL('**/#/calendar/month/**');
    await page.keyboard.press('ArrowRight');
    await page.waitForFunction(() => !document.querySelector('.active-view .loading-bar'));
    await page.keyboard.press('t');
    await page.keyboard.press('w');
    await page.waitForURL('**/#/calendar/week/**');
    await page.keyboard.press('?');
    await page.waitForURL('**/#/settings');
    await page.waitForFunction(() => document.activeElement.id === 'shortcutsCard');
    assert.equal(await page.locator('.shortcut-row').count(), 16);
    await page.locator('#shortcutsCard').screenshot({ path: path.join(shots, 'shortcuts.png') });
    await page.setViewportSize({ width: 760, height: 900 });
    await page.locator('#fontScaleInput').fill('20');
    await page.locator('#appearanceForm').scrollIntoViewIfNeeded();
    assert(await page.evaluate(() => document.body.scrollWidth <= innerWidth), 'narrow layout must not overflow at maximum font size');
    const narrowLeft = await page.locator('.appearance-themes').boundingBox();
    const narrowRight = await page.locator('.appearance-controls').boundingBox();
    assert(narrowRight.y > narrowLeft.y + narrowLeft.height);
    await page.locator('#appearanceForm').screenshot({ path: path.join(shots, 'appearance-narrow.png') });
    assert.deepEqual(errors, []);
    console.log('PASS Skill download, split appearance, live font, persistence, density and all shortcut scopes');
  } catch (e) {
    console.error(await page.evaluate(() => ({ url: location.href, focus: document.activeElement?.id || document.activeElement?.tagName, editing: !!document.querySelector('.modal.open, .inline-task-editor'), drawer: document.getElementById('dayDrawer').className, ddl: document.getElementById('ddlPopup').className, formError: document.getElementById('taskFormError').textContent, modal: document.getElementById('quickAddModal').className })));
    throw e;
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
