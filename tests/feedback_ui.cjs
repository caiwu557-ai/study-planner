const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const base = 'http://127.0.0.1:18765';
  const today = new Intl.DateTimeFormat('sv-SE', { timeZone: 'Asia/Shanghai', year: 'numeric', month: '2-digit', day: '2-digit' }).format(new Date());
  const shots = path.join(__dirname, '../shots/feedback');
  fs.mkdirSync(shots, { recursive: true });
  async function goto(route) { await page.goto(base + '/#/' + route); await page.waitForFunction(() => !document.querySelector('.active-view .loading-bar')); }
  async function request(url, data) { const response = await context.request.post(base + url, { data }); assert(response.ok(), await response.text()); return response.json(); }
  try {
    await goto('home/' + today);
    await page.locator('#reviewList .toggle-review').first().waitFor();
    assert.equal(await page.locator('#headerQuickAdd').count(), 0);
    const before = await page.locator('#sidebarToggle').boundingBox();
    await page.locator('#sidebarToggle').click();
    await page.waitForTimeout(300);
    const after = await page.locator('#sidebarToggle').boundingBox();
    assert(Math.abs(before.y - after.y) < 1, 'toggle must stay at same vertical position');
    assert(await page.locator('#quickAddBtn > svg').isVisible());
    await page.locator('#quickAddBtn').click();
    await page.locator('#quickAddModal.open').waitFor();
    await page.keyboard.press('Escape');
    await page.locator('#reviewList .toggle-review').first().click();
    await page.locator('#reviewList .is-done').waitFor();
    await goto('reviews');
    await page.locator('#reviewsView .is-done .toggle-review').click();
    await page.locator('#reviewsView .review-item:not(.is-done)').waitFor();
    await page.locator('#reviewsView .review-item:not(.is-done) .toggle-review').click();
    await page.locator('#reviewsView .is-done').waitFor();
    await page.locator('#reviewsView .is-done .toggle-review').click();
    await page.locator('#reviewsView .review-item:not(.is-done)').waitFor();
    console.log('PASS home and review-list completion / undo');

    await goto('todos/all');
    assert.equal(await page.locator('[data-view="tasks"]').count(), 0);
    assert(await page.locator('#todosView').getByText('未安排日期的测试任务', { exact: true }).isVisible());
    const row = page.locator('#todosView .task-item').filter({ hasText: '示例项目材料' }).first();
    await row.locator('.edit-task').click();
    await row.locator('[name="title"]').fill('修改后的测试任务');
    await row.locator('[name="notes"]').fill('执行步骤\n1. 写初稿\n2. 检查材料');
    await row.locator('button[type="submit"]').click();
    await page.locator('#todosView .task-title').filter({ hasText: '修改后的测试任务' }).first().waitFor();
    await page.locator('#todosView .task-item').filter({ hasText: '修改后的测试任务' }).first().locator('.delete-task').click();
    await page.locator('#actionToast.show .action-toast-copy').filter({ hasText: '任务已删除' }).waitFor();
    const startOffset = await page.locator('.action-toast-edge rect').evaluate(el => Number(el.style.strokeDashoffset));
    await page.waitForTimeout(1100);
    const endOffset = await page.locator('.action-toast-edge rect').evaluate(el => Number(el.style.strokeDashoffset));
    assert(endOffset > startOffset + 8, 'edge countdown must shorten');
    assert(Number((await page.locator('.action-toast-countdown').textContent()).replace('s', '')) < 8);
    await page.locator('#toggleTrash').click();
    const trash = page.locator('#trashList .is-trash').first();
    await trash.waitFor();
    const metrics = await trash.evaluate(el => ({ height: el.offsetHeight, bodyWidth: el.querySelector('.task-body').offsetWidth, columns: getComputedStyle(el).gridTemplateColumns }));
    assert(metrics.height < 150 && metrics.bodyWidth > 300, JSON.stringify(metrics));
    await page.screenshot({ path: path.join(shots, 'todo-trash-countdown.png') });
    await trash.locator('.restore-task').click();
    await page.locator('#todosView .task-title').filter({ hasText: '修改后的测试任务' }).first().waitFor();
    console.log('PASS inline edit, delete, countdown and compact trash restore');

    await goto('ddls/all');
    const ddlRow = page.locator('#ddlsView .ddl-item').first();
    await ddlRow.waitFor();
    assert.equal(await ddlRow.locator('.toggle-task').count(), 0);
    await ddlRow.locator('.edit-task').click();
    await ddlRow.locator('[name="notes"]').fill('到期清单原地修改');
    await ddlRow.locator('button[type="submit"]').click();
    await page.waitForFunction(() => !document.querySelector('#ddlsView .inline-task-editor'));
    assert(await page.locator('#ddlsView #trashCard').isVisible());
    await goto('tasks');
    await page.waitForURL('**/#/todos/all');
    console.log('PASS deadline management and legacy route');

    await goto('calendar/week/' + today);
    await page.locator('.week-event').waitFor();
    assert.equal(await page.locator('#calendarFilters').isVisible(), false);
    assert.equal(await page.locator('[data-mode="week"]').textContent(), '周课表');
    await page.locator('[data-mode="month"]').click();
    await page.locator('#monthBoard.active-board').waitFor();
    await page.locator('.cal-event.review').first().waitFor();
    assert(await page.locator('.cal-event.task').count() > 0);
    assert(await page.locator('.cal-event.ddl').count() > 0);
    assert.equal(await page.locator('.cal-event.course').count(), 0);
    assert.equal(await page.locator('[data-mode="month"]').textContent(), '月清单');
    await page.screenshot({ path: path.join(shots, 'month-list.png') });
    await page.locator('[data-filter="review"]').click();
    assert.equal(await page.locator('.cal-event.task,.cal-event.ddl').count(), 0);
    console.log('PASS weekly timetable / monthly lists and filters');

    await goto('settings');
    const cards = page.locator('.settings-grid > .board-card');
    assert.equal(await cards.count(), 5);
    const boxes = await cards.evaluateAll(els => els.map(el => el.getBoundingClientRect().y));
    assert(boxes.every((y, i) => i === 0 || y > boxes[i - 1]), 'settings must stack horizontally');
    await page.locator('#scheduleFile').setInputFiles(path.join(__dirname, '../static/schedule-example.json'));
    await page.waitForFunction(() => !document.getElementById('importScheduleBtn').disabled);
    await page.locator('#scheduleDropZone').evaluate((zone, json) => {
      const transfer = new DataTransfer();
      transfer.items.add(new File([json], 'schedule-drop.json', { type: 'application/json' }));
      zone.dispatchEvent(new DragEvent('drop', { bubbles: true, cancelable: true, dataTransfer: transfer }));
    }, fs.readFileSync(path.join(__dirname, '../static/schedule-example.json'), 'utf8'));
    await page.locator('#schedulePreview').filter({ hasText: 'schedule-drop.json' }).waitFor();
    await page.locator('#importScheduleBtn').click();
    await page.locator('#schedulePreview').filter({ hasText: '载入完成' }).waitFor();
    await page.route('**/api/ai/test', route => route.fulfill({ json: { ok: true, model: 'test-model' } }));
    await page.locator('#aiKeyInput').fill('test-only-key');
    await page.locator('#testApiBtn').click();
    await page.locator('#apiTestStatus').filter({ hasText: '连接成功' }).waitFor();
    assert.equal(await page.locator('#aiKeyInput').inputValue(), 'test-only-key', 'standalone testing must not save');
    await page.locator('#aiForm button[type="submit"]').click();
    await page.waitForFunction(() => document.getElementById('aiKeyInput').value === '');
    await page.locator('#apiTestStatus').filter({ hasText: '连接成功' }).waitFor();
    assert.equal(await page.locator('#aiKeyInput').inputValue(), '');
    await page.screenshot({ path: path.join(shots, 'settings.png'), fullPage: true });
    await page.route('**/api/ai/test', route => route.fulfill({ status: 503, json: { error: 'API Key 无效或已过期' } }));
    await page.locator('#testApiBtn').click();
    await page.locator('#apiTestStatus').filter({ hasText: '连接失败' }).waitFor();
    await page.route('**/api/ai/parse', route => route.fulfill({ json: { parsed: { title: 'AI 整理任务', type: 'assignment', planned_date: today, notes: '执行步骤\n1. 阅读讲义\n2. 写初稿\n\n注意事项\n1. 提交 PDF' } } }));
    await page.locator('#quickAddBtn').click();
    await page.locator('#aiInput').fill('凌乱输入测试');
    await page.locator('#aiParseBtn').click();
    await page.waitForFunction(() => document.getElementById('taskNotes').value.includes('执行步骤'));
    assert((await page.locator('#taskNotes').inputValue()).includes('\n\n注意事项'));
    await page.screenshot({ path: path.join(shots, 'formatted-notes.png') });
    await page.keyboard.press('Escape');
    await page.setViewportSize({ width: 760, height: 900 });
    await goto('todos/all');
    await page.locator('#toggleTrash').click();
    assert(await page.locator('#quickAddBtn > svg').isVisible());
    assert(await page.locator('#sidebarToggle').isVisible());
    assert(await page.evaluate(() => document.body.scrollWidth <= innerWidth));
    assert.deepEqual(errors, []);
    console.log('PASS schedule import, AI feedback, formatted notes and narrow layout');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
